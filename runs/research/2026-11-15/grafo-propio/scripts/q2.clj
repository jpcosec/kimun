(require '[clojure.edn :as edn] '[clojure.string :as str])
(def g (edn/read-string (slurp "/tmp/kimun-planes/grafo-propio/grafo.edn")))
(def es (:edges g))
(defn dirof [n] (let [p (str/split (str/replace n "kimun." "") #"\.")] (str/join "." (butlast p))))
(defn top [n] (first (str/split (str/replace n "kimun." "") #"\.")))
(println "--surface->cli / lower->upper")
(doseq [[a b] es :when (or (and (#{"surface" "graph" "host" "kernel"} (top a)) (= "cli" (top b)))
                           (and (= "kernel" (top a)) (not= "kernel" (top b)))
                           (and (= "host" (top a)) (#{"surface" "graph" "cli"} (top b)))
                           (and (= "surface" (top a)) (= "graph" (top b)))
                           (and (= "graph" (top a)) (#{"cli" "host"} (top b))))] (println a "->" b))
(println "--graph->surface") (doseq [[a b] es :when (and (= "graph" (top a)) (= "surface" (top b)))] (println a "->" b))
(println "--legacy") (doseq [[a b] es :when (or (str/includes? a "legacy") (str/includes? b "legacy"))] (println a "->" b))
(println "--fan-in of cli.* by non-cli") 
(doseq [n (:nodes g) :when (and (str/starts-with? (:ns n) "kimun.cli") (not (str/includes? (:ns n) "commands")))] (println (:ns n) (:lines n) (count (filter #(= (second %) (:ns n)) es))))
(println "--external requires")
(println (frequencies (for [n (:nodes g) r (:requires n) :when (not (str/starts-with? r "kimun.")) ] (first (str/split r #"\.")))))
(println "--ns by dir") (doseq [[d ns] (sort-by key (group-by (comp dirof :ns) (:nodes g)))] (println d (count ns) (reduce + (map :lines ns)) (reduce + (map :defn-public ns))))
(println "--cli.commands list") (doseq [n (sort-by (comp - :lines) (filter #(str/includes? (:ns %) "cli.commands") (:nodes g)))] (println (:lines n) (:defn-public n) (:ns n)))
