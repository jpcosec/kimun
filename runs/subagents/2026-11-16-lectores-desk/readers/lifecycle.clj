(reading (files "desk/lifecycle/**/*.md")
  (fn [doc]
    (when-let [f (:front doc)]
      (let [id (symbol (basename (:path doc)))]
        (if (contains? f "source_id")
          (do (isa id LifecycleRelation)
              (each relation-source id f "source_id")
              (each relation-target id f "target_id")
              (each relation-type id f "relation_type")
              (each has-name id f "name")
              (each has-direction id f "direction")
              (each has-cardinality id f "cardinality")
              (each has-axis id f "axis")
              (each has-source-types id f "source_types")
              (each has-target-types id f "target_types"))
          (do (isa id LifecycleRule)
              (each has-subject id f "subject")
              (each has-severity id f "severity")
              (each has-moment id f "moment")))))))
